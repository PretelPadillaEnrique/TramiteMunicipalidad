CREATE TABLE AREA (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 4) PRIMARY KEY,
    nombre VARCHAR(255),
    descripcion VARCHAR(255),
    estado VARCHAR(255)
);

CREATE TABLE CATEGORIA (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 4) PRIMARY KEY,
    nombre VARCHAR(255),
    plazoAtencion INTEGER,
    estado VARCHAR(255),
    area_id BIGINT,
    FOREIGN KEY (area_id) REFERENCES AREA(id)
);

CREATE TABLE USUARIO (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 5) PRIMARY KEY,
    nombre VARCHAR(255),
    correo VARCHAR(255),
    password VARCHAR(255),
    rol VARCHAR(255) NOT NULL CHECK (rol IN ('Administrador', 'Usuario')),
    estado VARCHAR(255),
    area_id BIGINT,
    FOREIGN KEY (area_id) REFERENCES AREA(id)
);

CREATE TABLE EXPEDIENTE (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 25) PRIMARY KEY,
    folio VARCHAR(255),
    ciudadanoNombre VARCHAR(255),
    ciudadanoDni VARCHAR(255),
    ciudadanoContacto VARCHAR(255),
    fechaRegistro DATE,
    fechaLimite DATE,
    motivoReprogramacion VARCHAR(255),
    estado VARCHAR(255),
    activo BOOLEAN DEFAULT TRUE NOT NULL,
    categoria_id BIGINT,
    areaActual_id BIGINT,
    usuarioRegistro_id BIGINT,
    usuarioUltimoCambio_id BIGINT,
    FOREIGN KEY (categoria_id) REFERENCES CATEGORIA(id),
    FOREIGN KEY (areaActual_id) REFERENCES AREA(id),
    FOREIGN KEY (usuarioRegistro_id) REFERENCES USUARIO(id),
    FOREIGN KEY (usuarioUltimoCambio_id) REFERENCES USUARIO(id)
);

CREATE TABLE ADJUNTO (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 2) PRIMARY KEY,
    nombreArchivo VARCHAR(255),
    contenido BLOB NOT NULL,
    fechaCarga DATE,
    expediente_id BIGINT,
    FOREIGN KEY (expediente_id) REFERENCES EXPEDIENTE(id)
);
